def emit():
    maint = parse_maintenance()
    ings = parse_ingredients()
    hk = HK_ITEMS

    lines = []
    A = lines.append
    A("// AUTO-GENERATED by scripts/parse-stores.py — do not edit by hand.")
    A("// Sources: Maintainance Materials.xlsx, Store Inventory On Daily")
    A("// Basis.xlsx, and the client's HK Requirement sheet.")
    A(f"// {len(maint)} maintenance, {len(ings)} ingredients, {len(hk)} housekeeping.")
    A("")
    A("export interface MaintItemSeed { name: string; category: string; unit: string }")
    A("export interface IngredientSeed { sku: string; name: string; unit: string; openingQty: number; openingAvgCost: number }")
    A("export interface HkItemSeed { name: string; category: string; unit: string }")
    A("")
    A("export const maintenanceItemSeed: MaintItemSeed[] = [")
    for m in maint:
        A(f'  {{ name: {ts(m["name"])}, category: {ts(m["category"])}, unit: {ts(m["unit"])} }},')
    A("];")
    A("")
    A("export const ingredientSeed: IngredientSeed[] = [")
    for i in ings:
        A(f'  {{ sku: {ts(i["sku"])}, name: {ts(i["name"])}, unit: {ts(i["unit"])}, openingQty: {i["openingQty"]}, openingAvgCost: {i["openingAvgCost"]} }},')
    A("];")
    A("")
    A("export const housekeepingItemSeed: HkItemSeed[] = [")
    for h in hk:
        A(f'  {{ name: {ts(h[0])}, category: {ts(h[1])}, unit: {ts(h[2])} }},')
    A("];")
    A("")

    out_path = "indefine-kitchen/prisma/seed-data/stores.ts"
    os.makedirs(os.path.dirname(out_path), exist_ok=True)
    with open(out_path, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines))
    print(f"Wrote {out_path}: {len(maint)} maint, {len(ings)} ingredients, {len(hk)} hk")


if __name__ == "__main__":
    emit()
