"""Parse the client's store files into a TypeScript seed module:
  - Maintainance Materials.xlsx  -> MaintenanceItem rows
  - Store Inventory On Daily Basis.xlsx -> Ingredient rows (kitchen store)
  - HK requirement list (typed inline) -> HousekeepingItem rows

Writes prisma/seed-data/stores.ts. Idempotent keys:
  Ingredient    -> sku  (STR-####)
  MaintenanceItem / HousekeepingItem -> name (both @@unique on name)
"""
import json
import re
import os
import openpyxl


def ts(s):
    return json.dumps(s, ensure_ascii=False) if s is not None else "null"


def num(x, places=3):
    try:
        return round(float(x), places)
    except (TypeError, ValueError):
        return 0


# Maintenance items that are plumbing/mechanical, not electrical.
GENERAL_HINTS = ("water tape", "spray gun", "shower", "pipe")


def parse_maintenance():
    wb = openpyxl.load_workbook(
        "H:/Cater/Catering/Maintainance Materials.xlsx",
        data_only=True, read_only=True,
    )
    ws = wb["Sheet1"]
    out, seen = [], set()
    for r in ws.iter_rows(values_only=True):
        if not r or not r[0] or not str(r[0]).strip().isdigit():
            continue
        if len(r) < 2 or not r[1]:
            continue
        name = re.sub(r"\s+", " ", str(r[1]).strip())
        key = name.lower()
        if key in seen:
            continue
        seen.add(key)
        cat = "GENERAL" if any(h in key for h in GENERAL_HINTS) else "ELECTRICAL"
        out.append({"name": name, "category": cat, "unit": "piece"})
    return out


def parse_ingredients():
    wb = openpyxl.load_workbook(
        "H:/Cater/Catering/Store Inventory On Daily Basis.xlsx",
        data_only=True, read_only=True,
    )
    ws = wb["Sheet1"]
    rows = list(ws.iter_rows(values_only=True))
    out, seen = [], set()
    n = 0
    for r in rows[2:]:
        if not r or r[1] is None or not str(r[1]).strip():
            continue
        name = re.sub(r"\s+", " ", str(r[1]).strip())
        key = name.lower()
        if key in seen:
            continue
        seen.add(key)
        n += 1
        unit = str(r[3]).strip() if len(r) > 3 and r[3] else "kg"
        inv = num(r[2]) if len(r) > 2 else 0
        rate = num(r[4], 4) if len(r) > 4 else 0
        out.append(
            {
                "sku": f"STR-{n:04d}",
                "name": name,
                "unit": unit,
                "openingQty": inv,
                "openingAvgCost": rate,
            }
        )
    return out


